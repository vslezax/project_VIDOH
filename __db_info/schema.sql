CREATE TABLE "tickets" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "event_id" bigint NOT NULL,
  "name" varchar(150) NOT NULL,
  "description" text,
  "price" numeric(12,2) NOT NULL DEFAULT 0,
  "currency" char(3) NOT NULL DEFAULT 'RUB',
  "tickets_count" integer,
  "sold_count" integer NOT NULL DEFAULT 0,
  "external_url" text,
  "sort_order" integer NOT NULL DEFAULT 0,
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL,
  CONSTRAINT "tickets_price_nonnegative" CHECK (price >= 0),
  CONSTRAINT "tickets_count_positive" CHECK (tickets_count IS NULL OR tickets_count > 0),
  CONSTRAINT "tickets_sold_nonnegative" CHECK (sold_count >= 0),
  CONSTRAINT "tickets_sold_le_count" CHECK (tickets_count IS NULL OR sold_count <= tickets_count),
  CONSTRAINT "tickets_sort_nonnegative" CHECK (sort_order >= 0)
);

CREATE TABLE "promo_codes" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "code" varchar(64) UNIQUE NOT NULL,
  "event_id" bigint,
  "discount_type" promo_discount_type NOT NULL,
  "discount_value" numeric(12,2) NOT NULL,
  "max_uses" integer,
  "used_count" integer NOT NULL DEFAULT 0,
  "valid_from" timestamptz,
  "valid_to" timestamptz,
  "is_active" boolean NOT NULL DEFAULT true,
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL,
  CONSTRAINT "promo_percent_range" CHECK (discount_type <> 'percent' OR (discount_value > 0 AND discount_value <= 100)),
  CONSTRAINT "promo_fixed_positive" CHECK (discount_type <> 'fixed' OR discount_value > 0),
  CONSTRAINT "promo_max_uses_positive" CHECK (max_uses IS NULL OR max_uses > 0),
  CONSTRAINT "promo_used_nonnegative" CHECK (used_count >= 0),
  CONSTRAINT "promo_used_le_max" CHECK (max_uses IS NULL OR used_count <= max_uses),
  CONSTRAINT "promo_valid_range" CHECK (valid_from IS NULL OR valid_to IS NULL OR valid_from < valid_to)
);

CREATE TABLE "user_favorites" (
