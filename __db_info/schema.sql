CREATE TABLE "order_items" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "order_id" bigint NOT NULL,
  "ticket_id" bigint NOT NULL,
  "quantity" smallint NOT NULL,
  "unit_price" numeric(12,2) NOT NULL,
  "total_price" numeric(12,2) NOT NULL,
  "event_title_snapshot" varchar(255),
  "ticket_name_snapshot" varchar(150),
  CONSTRAINT "order_items_quantity_positive" CHECK (quantity > 0),
  CONSTRAINT "order_items_unit_price_nonnegative" CHECK (unit_price >= 0),
  CONSTRAINT "order_items_total_price_nonnegative" CHECK (total_price >= 0),
  CONSTRAINT "order_items_total_matches" CHECK (total_price = quantity * unit_price)
