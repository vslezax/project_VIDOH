  'service_rules',
  'payment_rules',
  'safety_rules',
  'refund_policy',
  'other'
);

CREATE TYPE "review_status" AS ENUM (
  'pending',
  'published',
  'rejected'
);

CREATE TYPE "order_status" AS ENUM (
  'pending',
  'paid',
  'cancelled',
  'refunded',
  'failed'
