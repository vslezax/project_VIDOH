  'cancelled',
  'finished'
);

CREATE TYPE "media_type" AS ENUM (
  'image',
  'video'
);

CREATE TYPE "media_role" AS ENUM (
  'user_avatar',
  'event_cover',
  'event_big_cover',
  'event_gallery',
  'organizer_logo',
  'organizer_cover'
