CREATE TABLE "users" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "uuid" uuid UNIQUE NOT NULL,
  "email" citext UNIQUE,
  "phone" varchar(20) UNIQUE,
  "password_hash" text NOT NULL,
  "name" varchar(100) NOT NULL,
  "nickname" varchar(150) UNIQUE NOT NULL,
  "avatar_media_id" bigint,
  "status" user_status NOT NULL DEFAULT 'pending',
  "email_verified_at" timestamptz,
  "phone_verified_at" timestamptz,
  "last_login_at" timestamptz,
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL,
  "deleted_at" timestamptz,
  CONSTRAINT "users_email_or_phone_required" CHECK (email IS NOT NULL OR phone IS NOT NULL)
);

CREATE TABLE "event_schedules" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "event_id" bigint NOT NULL,
  "kind" schedule_kind NOT NULL,
  "start_at" timestamptz,
  "recurrence" varchar(255),
  "utc_offset" varchar(6) NOT NULL,
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL,
  CONSTRAINT "event_schedules_kind_fields" CHECK ((kind = 'once' AND start_at IS NOT NULL AND recurrence IS NULL) OR (kind = 'recurring' AND recurrence IS NOT NULL))
);

CREATE TABLE "user_sessions" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" bigint NOT NULL,
  "refresh_token_hash" varchar(255) UNIQUE NOT NULL,
  "user_agent" varchar(255),
  "ip" inet,
  "expires_at" timestamptz NOT NULL,
  "revoked_at" timestamptz,
  "created_at" timestamptz NOT NULL
);

CREATE TABLE "organizers" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "uuid" uuid UNIQUE NOT NULL,
  "slug" varchar(160) UNIQUE NOT NULL,
  "name" varchar(200) NOT NULL,
  "short_description" varchar(500),
  "description" text,
  "avatar_media_id" bigint,
  "cover_media_id" bigint,
  "legal_form" organizer_legal_form NOT NULL DEFAULT 'legal_entity',
  "inn" varchar(12),
  "ogrn" varchar(15),
  "status" organizer_status NOT NULL DEFAULT 'draft',
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL,
  "deleted_at" timestamptz,
  CONSTRAINT "organizers_inn_for_legal_entity" CHECK (legal_form <> 'legal_entity' OR (inn IS NOT NULL AND length(inn) IN (10, 12))),
  CONSTRAINT "organizers_ogrn_for_legal_entity" CHECK (legal_form <> 'legal_entity' OR (ogrn IS NOT NULL AND length(ogrn) IN (13, 15)))
);

CREATE TABLE "countries" (
  "id" smallserial PRIMARY KEY,
  "name" varchar(100) NOT NULL,
  "iso" char(2) UNIQUE NOT NULL,
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL
);

CREATE TABLE "cities" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "country_id" smallint NOT NULL,
  "name" varchar(150) NOT NULL,
  "slug" varchar(160) NOT NULL,
  "lat" numeric(9,6),
  "lng" numeric(9,6),
  "timezone" varchar(64) NOT NULL DEFAULT 'UTC',
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL
);

CREATE TABLE "venues" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "city_id" bigint NOT NULL,
  "slug" varchar(180) NOT NULL,
  "name" varchar(200) NOT NULL,
  "address" text NOT NULL,
  "metro_station_id" bigint,
  "lat" numeric(9,6),
  "lng" numeric(9,6),
  "capacity" integer,
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL,
  CONSTRAINT "venues_capacity_positive" CHECK (capacity IS NULL OR capacity > 0),
  CONSTRAINT "venues_lat_lng_pair" CHECK ((lat IS NULL AND lng IS NULL) OR (lat IS NOT NULL AND lng IS NOT NULL)),
  CONSTRAINT "venues_lat_range" CHECK (lat IS NULL OR lat BETWEEN -90 AND 90),
  CONSTRAINT "venues_lng_range" CHECK (lng IS NULL OR lng BETWEEN -180 AND 180)
);

CREATE TABLE "categories" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "slug" varchar(160) UNIQUE NOT NULL,
  "name" varchar(150) NOT NULL,
  "description" text,
  "icon_media_id" bigint,
  "sort_order" integer NOT NULL DEFAULT 0,
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL,
  "deleted_at" timestamptz
);

CREATE TABLE "media" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "storage_key" text UNIQUE NOT NULL,
  "url" text NOT NULL,
  "type" media_type NOT NULL,
  "alt" varchar(255),
  "width" integer,
  "height" integer,
  "size_bytes" bigint,
  "uploaded_by" bigint,
  "created_at" timestamptz NOT NULL,
  CONSTRAINT "media_width_positive" CHECK (width IS NULL OR width > 0),
  CONSTRAINT "media_height_positive" CHECK (height IS NULL OR height > 0),
  CONSTRAINT "media_size_nonnegative" CHECK (size_bytes IS NULL OR size_bytes >= 0)
);

CREATE TABLE "event_media" (
  "event_id" bigint NOT NULL,
  "media_id" bigint NOT NULL,
  "role" media_role NOT NULL DEFAULT 'event_cover',
  "sort_order" integer NOT NULL DEFAULT 0,
  "caption" varchar(255),
  CONSTRAINT "event_media_gallery_sort_nonnegative" CHECK (role NOT IN ('event_gallery') OR sort_order >= 0),
  PRIMARY KEY ("event_id", "media_id")
);

CREATE TABLE "events" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "uuid" uuid UNIQUE NOT NULL,
  "slug" varchar(200) UNIQUE NOT NULL,
  "title" varchar(255) NOT NULL,
  "short_description" varchar(500),
  "description" text,
  "venue_id" bigint,
  "online_url" text,
  "status" event_status NOT NULL DEFAULT 'unpublished',
  "age_rating" smallint,
  "capacity" integer,
  "currency" char(3) NOT NULL DEFAULT 'RUB',
  "published_at" timestamptz,
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL,
  "deleted_at" timestamptz,
  CONSTRAINT "events_venue_or_online" CHECK (venue_id IS NOT NULL OR online_url IS NOT NULL),
  CONSTRAINT "events_age_rating_allowed" CHECK (age_rating IS NULL OR age_rating IN (0, 6, 12, 16, 18)),
  CONSTRAINT "events_capacity_positive" CHECK (capacity IS NULL OR capacity > 0),
  CONSTRAINT "events_published_requires_published_at" CHECK (status <> 'published' OR published_at IS NOT NULL)
);

CREATE TABLE "event_organizers" (
  "event_id" bigint NOT NULL,
  "organizer_id" bigint NOT NULL,
  "is_primary" boolean NOT NULL DEFAULT false,
  "role" varchar(100),
  "sort_order" integer NOT NULL DEFAULT 0,
  "confirmed_at" timestamptz,
  CONSTRAINT "event_organizers_sort_nonnegative" CHECK (sort_order >= 0),
  PRIMARY KEY ("event_id", "organizer_id")
);

CREATE TABLE "event_categories" (
  "event_id" bigint NOT NULL,
  "category_id" bigint NOT NULL,
  "is_primary" boolean NOT NULL DEFAULT false,
  "sort_order" integer NOT NULL DEFAULT 0,
  CONSTRAINT "event_categories_sort_nonnegative" CHECK (sort_order >= 0),
  PRIMARY KEY ("event_id", "category_id")
);

CREATE TABLE "event_links" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "event_id" bigint NOT NULL,
  "type" link_type NOT NULL,
  "url" text NOT NULL,
  "title" varchar(150),
  "sort_order" integer NOT NULL DEFAULT 0,
  CONSTRAINT "event_links_sort_nonnegative" CHECK (sort_order >= 0)
