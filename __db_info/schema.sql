CREATE TYPE "promo_discount_type" AS ENUM (
  'percent',
  'fixed'
);

CREATE TYPE "schedule_kind" AS ENUM (
  'once',
  'recurring'
);

CREATE TYPE "contact_type" AS ENUM (
  'phone',
  'email',
  'vk',
  'telegram',
  'instagram',
  'website',
  'other'
);

CREATE TYPE "payment_status" AS ENUM (
  'pending',
  'succeeded',
  'failed',
  'refunded',
  'cancelled'
